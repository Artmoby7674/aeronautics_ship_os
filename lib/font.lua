function Font.textWidth(str)
    str = tostring(str or "")
    if #str == 0 then return 0 end
    return #str * Font.advance - (Font.advance - Font.width)
end

-- Longest prefix of str that fits in max_w pixels
function Font.fit(str, max_w)
    str = tostring(str or "")
    if max_w < 1 then return "" end
    if Font.textWidth(str) <= max_w then return str end
    local lo, hi = 0, #str
    while lo < hi do
        local mid = math.ceil((lo + hi) / 2)
        if Font.textWidth(str:sub(1, mid)) <= max_w then
            lo = mid
        else
            hi = mid - 1
        end
    end
    return str:sub(1, lo)
end

-- Dense row tables (every index 1..width filled) — required by drawPixels
function Font.render(str, color, bg)
    str = tostring(str or "")
    local fill = bg or -1
    local total_w = Font.textWidth(str)
    if total_w < 1 then return {}, 0 end

    local rows = {}
    for r = 1, Font.height do
        local row = {}
        for c = 1, total_w do
            row[c] = fill
        end
        rows[r] = row
    end

    local col = 0
    for i = 1, #str do
        local ch = str:sub(i, i):upper()
        local g = G[ch] or G["?"]
        for r = 1, Font.height do
            local line = g[r]
            local row = rows[r]
            for c = 1, Font.width do
                if line:sub(c, c) == "1" then
                    row[col + c] = color
                end
            end
        end
        col = col + Font.advance
    end

    return rows, total_w
end

return Font
